def get_svg_xml(name: str, color: str = "#e4e4e7", size: int = 16) -> str:
    body = SVG_PATHS.get(name, SVG_PATHS["sparkles"])
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{body}</svg>"""


def get_icon(name: str, color: str = "#e4e4e7", size: int = 15) -> QIcon:
    svg_xml = get_svg_xml(name, color, size)
    renderer = QSvgRenderer(QByteArray(svg_xml.encode("utf-8")))
    scale = 2
    px = QPixmap(size * scale, size * scale)
    px.fill(Qt.GlobalColor.transparent)
    painter = QPainter(px)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter, QRectF(0, 0, size * scale, size * scale))
    painter.end()
    px.setDevicePixelRatio(scale)
    return QIcon(px)
